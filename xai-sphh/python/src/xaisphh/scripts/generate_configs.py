"""
Generates YAML experiment configs for the full evaluation matrix and parameter sweeps.

Full matrix: 4 techniques x 6 domains x 10 instances x 5 seeds
Sweep configs: Late Acceptance list lengths and population sizes.

Item 7.
"""

from __future__ import annotations

import argparse
from pathlib import Path


TECHNIQUES: list[str] = ["SP-CF-LA", "SP-CF-AILTA", "SP-SR-LA", "MP-CF"]
DOMAINS:    list[str] = ["SAT", "BinPacking", "FlowShop", "TSP", "VRP", "PersonnelScheduling"]
INSTANCES:  list[int] = list(range(10))
SEEDS:      list[int] = [42, 123, 456, 789, 1000]

LA_LIST_LENGTHS: list[int]  = [1, 5, 50, 100, 500, 1000]
POP_SIZES:       list[int]  = [5, 10, 20, 50]

_TEMPLATE = """\
# Auto-generated by generate_configs.py -- do not edit by hand.
techniqueName: {technique}
domain: {domain}
instanceIndex: {instance}
seed: {seed}
budgetType: iterations
budgetValue: 100000
outputDirectory: data/raw/traces
techniqueParameters:
{params}"""

_LA_SWEEP_TEMPLATE = """\
# Auto-generated LA sweep config.
techniqueName: SP-CF-LA
domain: {domain}
instanceIndex: 0
seed: 42
budgetType: iterations
budgetValue: 100000
outputDirectory: data/raw/traces/sweep/la_L{list_length}
techniqueParameters:
  listLength: {list_length}"""

_POP_SWEEP_TEMPLATE = """\
# Auto-generated population size sweep config.
techniqueName: MP-CF
domain: {domain}
instanceIndex: 0
seed: 42
budgetType: iterations
budgetValue: 100000
outputDirectory: data/raw/traces/sweep/mp_pop{pop_size}
techniqueParameters:
  populationSize: {pop_size}"""


def _technique_params(technique: str) -> str:
    """Return the techniqueParameters block for the given technique."""
    if technique == "SP-CF-LA":
        return "  listLength: 50"
    if technique == "SP-CF-AILTA":
        return "  # No additional parameters required for AILTA."
    if technique == "SP-SR-LA":
        return "  listLength: 50"
    if technique == "MP-CF":
        return "  populationSize: 10"
    return "  # No additional parameters."


def generate_matrix_configs(output_dir: Path) -> int:
    """Write one YAML config per (technique, domain, instance, seed) combination.

    :param output_dir: directory in which YAML files are written
    :return: number of files written
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    count = 0
    for tech in TECHNIQUES:
        for dom in DOMAINS:
            for inst in INSTANCES:
                for seed in SEEDS:
                    stem = f"{tech}_{dom}_{inst}_{seed}"
                    config = _TEMPLATE.format(
                        technique=tech,
                        domain=dom,
                        instance=inst,
                        seed=seed,
                        params=_technique_params(tech),
                    )
                    (output_dir / f"{stem}.yaml").write_text(config, encoding="utf-8")
                    count += 1
    return count


def generate_sweep_configs(output_dir: Path) -> int:
    """Write YAML sweep configs for list-length and population-size sweeps.

    :param output_dir: directory in which YAML files are written
    :return: number of files written
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    count = 0

    la_dir  = output_dir / "la_sweep"
    pop_dir = output_dir / "pop_sweep"
    la_dir.mkdir(exist_ok=True)
    pop_dir.mkdir(exist_ok=True)

    for length in LA_LIST_LENGTHS:
        config = _LA_SWEEP_TEMPLATE.format(domain="SAT", list_length=length)
        (la_dir / f"SP-CF-LA_SAT_0_42_L{length}.yaml").write_text(config, encoding="utf-8")
        count += 1

    for size in POP_SIZES:
        config = _POP_SWEEP_TEMPLATE.format(domain="SAT", pop_size=size)
        (pop_dir / f"MP-CF_SAT_0_42_pop{size}.yaml").write_text(config, encoding="utf-8")
        count += 1

    return count


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate YAML experiment configs for the full evaluation matrix."
    )
    parser.add_argument(
        "--out", type=Path, default=Path("config/generated"),
        help="Output directory for generated YAML files (default: config/generated)."
    )
    parser.add_argument(
        "--sweeps-only", action="store_true",
        help="Generate only parameter sweep configs, not the full matrix."
    )
    args = parser.parse_args()

    if not args.sweeps_only:
        n = generate_matrix_configs(args.out / "matrix")
        print(f"Written {n} matrix configs to {args.out / 'matrix'}.")

    n_sweep = generate_sweep_configs(args.out / "sweeps")
    print(f"Written {n_sweep} sweep configs to {args.out / 'sweeps'}.")


if __name__ == "__main__":
    main()
